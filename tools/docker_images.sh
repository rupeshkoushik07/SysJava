#!/usr/bin/env bash
#
# AUTHOR-SIDE: write docker_images/images.tsv and docker_images/IMAGES.md from
# the images present on the analysis host (tag -> digest, image ID), and copy
# the Dockerfiles of the locally rebuilt images. Called by build_artifact.sh.
#
#   tools/docker_images.sh <artifact dir> <jdk8 repo>
set -euo pipefail
ART="${1:?artifact dir}"; JDK8_REPO="${2:?jdk8 repo}"
OUT="$ART/docker_images"
mkdir -p "$OUT/dockerfiles"
rm -rf "$OUT/dockerfiles/jdk8-buster"
cp -a "$JDK8_REPO/DockerFiles/jdk8-buster" "$OUT/dockerfiles/jdk8-buster"

# tag | folder | how obtained | OS | JDK
IMAGES="
cassandra:5.0.8|1_latest_containers|official|Debian 12|17
zookeeper:3.9.5|1_latest_containers (also Storm's ZooKeeper)|official|Ubuntu 22.04|17.0.19
tomcat:11.0.22|1_latest_containers|official tomcat:11.0, retagged|Ubuntu 24.04|25.0.3
solr:10.0.0|1_latest_containers|official|Ubuntu 24.04|25.0.3
groovy:5.0.6|1_latest_containers|official|Ubuntu 24.04|21.0.11
orientdb:3.2.53|1_latest_containers|official orientdb:latest, retagged|Ubuntu 26.04|8u492-b09
jetty:12.1.10|1_latest_containers|official|Ubuntu 26.04|25.0.3
elasticsearch:7.1.0|1_latest_containers|docker.elastic.co/elasticsearch/elasticsearch:7.1.0, retagged|CentOS 7|12 (bundled)
storm:2.8.8|1_latest_containers|official storm:latest, retagged|Ubuntu 26.04|17.0.19
jruby:10.1.0.0|1_latest_containers|official|Ubuntu 24.04|21.0.11
storm:2.4.0-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/storm|Debian 10|Temurin 8u504-b01
solr:8.7.0-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/solr|Debian 10|Temurin 8u504-b01
elasticsearch:7.5.2-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/elasticsearch|Debian 10|Temurin 8u504-b01
groovy:4.0.0-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/groovy|Debian 10|Temurin 8u504-b01
jetty:9.4.51-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/jetty|Debian 10|Temurin 8u504-b01
zookeeper:3.7|2_swat4j_vs_sysjava (Storm's ZooKeeper)|official|Ubuntu 22.04|11.0.25
zookeeper:3.4.14-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/zookeeper|Debian 10|Temurin 8u504-b01
zookeeper:3.4.14|build stage of dockerfiles/jdk8-buster/zookeeper|official|Debian 10|8u292
tomcat:7.0-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/tomcat|Debian 10|Temurin 8u504-b01
tomcat:7.0|build stage of dockerfiles/jdk8-buster/tomcat|official|Debian 10|8u292
cassandra:3.0.29-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/cassandra|Debian 10|Temurin 8u504-b01
cassandra:3.0.29|build stage of dockerfiles/jdk8-buster/cassandra|official|Ubuntu 22.04|8u402-b06
orientdb:3.2.19-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/orientdb|Debian 10|Temurin 8u504-b01
orientdb:3.2.19|build stage of dockerfiles/jdk8-buster/orientdb|official|Ubuntu 22.04|8u372-b07
jruby:9.4.2.0-jdk8-buster|2_swat4j_vs_sysjava|built: dockerfiles/jdk8-buster/jruby|Debian 10|Temurin 8u504-b01
jruby:9.4.2.0|build stage of dockerfiles/jdk8-buster/jruby|official|Ubuntu 20.04|8u372-b07
debian:buster-slim|base of the ten built images|official|Debian 10|-
"

printf 'tag\tpull_ref\timage_id\tfolder\tobtained\tos\tjdk\n' > "$OUT/images.tsv"
{
    echo "# Docker images (generated by tools/docker_images.sh)"
    echo
    echo "Every image used for the shipped results. \`pull_ref\` is the registry digest:"
    echo "\`docker pull <pull_ref>\` gives the exact image. Built images have no registry"
    echo "digest; their local image ID is recorded for identification."
    echo
    echo "| Tag | Folder | Obtained | OS | JDK | Pull reference (digest) | Image ID |"
    echo "|---|---|---|---|---|---|---|"
} > "$OUT/IMAGES.md"
echo "$IMAGES" | while IFS='|' read -r tag folder how os jdk; do
    [ -n "$tag" ] || continue
    ref="$(docker image inspect -f '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' "$tag" 2>/dev/null || true)"
    id="$(docker image inspect -f '{{.Id}}' "$tag" 2>/dev/null || true)"
    case "$how" in built:*) ref="built-locally" ;; esac
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$tag" "${ref:-missing}" "${id:-missing}" "$folder" "$how" "$os" "$jdk" >> "$OUT/images.tsv"
    printf '| `%s` | %s | %s | %s | %s | `%s` | `%s` |\n' "$tag" "$folder" "$how" "$os" "$jdk" "${ref:-missing}" "${id:-missing}" >> "$OUT/IMAGES.md"
done
echo "docker_images: $(($(wc -l < "$OUT/images.tsv") - 1)) images"
