#!/usr/bin/env bash
#
# AUTHOR-SIDE: (re)build this artifact from the run trees on the analysis host.
# Reviewers do not need this script; it documents where every shipped file came
# from. Rerun it whenever the latest-versions / JDK 8 runs finish, then push the
# folder to the anonymous repository.
#
#   tools/build_artifact.sh                  # code, docs, Docker images; empty result folders
#   tools/build_artifact.sh --with-results   # also copy the results, STATUS.md and tables
#   tools/build_artifact.sh --with-latest-results   # only the results of 1_latest_containers
#
# What it does:
#   1. echotrace/          <- git archive of the detector commit (EchoTrace tool source)
#   2. 1_latest_containers/scripts/  <- driver + pipeline scripts used for that table
#      2_swat4j_vs_sysjava/scripts/  <- driver + pipeline scripts used for that table
#   3. syspart/            <- pinned SysPart build description
#   4. swat4j/             <- SWAT4J run/compare scripts and their small outputs
#   5. 1_latest_containers/results/<target>   <- Final_results_latest_versions
#      2_swat4j_vs_sysjava/sysjava_results/<target> <- Final_results_JDK8 (5 rebuilt images)
#      Container file copies (Dataset/, Dataset_symbolized/ ELFs and JARs) are left
#      out: they are regenerated by the pipeline from the public images. Every
#      callgraph.json is gzipped. Backup folders from bug-fix reruns are left out.
#   6. anonymise every shipped text file (home paths, user and org names)
#   7. regenerate the tables (tools/make_tables.py) and STATUS.md files
#
set -euo pipefail

ART="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TUT="${TUT:-$HOME/Tutorial}"
LATEST_REPO="${LATEST_REPO:-$TUT/EchoTrace_latest}"          # 1_latest_containers runs
JDK8_REPO="${JDK8_REPO:-$TUT/EchoTrace}"                     # 2_swat4j_vs_sysjava runs
DETECTOR_REPO="${DETECTOR_REPO:-$TUT/EchoTrace_clinit_build}" # tool source shipped
DETECTOR_COMMIT="${DETECTOR_COMMIT:-52628c4}"
SWAT4J_DIR="${SWAT4J_DIR:-$TUT/swat4j}"
SWAT4J_MAPPING="${SWAT4J_MAPPING:-$HOME/Prototype/swat4j_mapping.py}"
CODE_ONLY=1; LATEST_ONLY=0
case "${1:-}" in
    --with-results) CODE_ONLY=0 ;;
    --with-latest-results) CODE_ONLY=0; LATEST_ONLY=1 ;;   # table 2 stays placeholders
esac

LATEST_TARGETS=(cassandra_5.0.8 zookeeper_3.9.5 tomcat_11.0.22 solr_10.0.0 groovy_5.0.6
                orientdb_3.2.53 jetty_12.1.10 elasticsearch_7.1.0 storm_2.8.8 jruby_10.1.0.0)
JDK8_TARGETS=(zookeeper_3.4.14-jdk8-buster tomcat_7.0-jdk8-buster cassandra_3.0.29-jdk8-buster
              jetty_9.4.51-jdk8-buster storm_2.4.0-jdk8-buster orientdb_3.2.19-jdk8-buster
              elasticsearch_7.5.2-jdk8-buster solr_8.7.0-jdk8-buster groovy_4.0.0-jdk8-buster
              jruby_9.4.2.0-jdk8-buster)
# Earlier the official JDK 8 images; all ten are now rebuilt on Debian 10 (kept empty).
JDK8_OFFICIAL_TARGETS=()
JDK8_OFFICIAL_SRC="${JDK8_OFFICIAL_SRC:-}"

log() { echo "[build_artifact] $*"; }

# ------------------------------------------------------------------ 1. tool
log "echotrace/ <- ${DETECTOR_REPO} @ ${DETECTOR_COMMIT}"
rm -rf "$ART/echotrace"; mkdir -p "$ART/echotrace"
git -C "$DETECTOR_REPO" archive "$DETECTOR_COMMIT" | tar -x -C "$ART/echotrace"
# results/ and SysPartCode/ in the tool repo are old sample outputs / a stub; the
# table folders bring their own scripts/ and SysPart is built separately (syspart/).
rm -rf "$ART/pipelines" "$ART/echotrace_patches"   # older layout
rm -rf "$ART/echotrace/results" "$ART/echotrace/scripts" "$ART/echotrace/SysPartCode"
git -C "$DETECTOR_REPO" rev-parse "$DETECTOR_COMMIT" > "$ART/echotrace/COMMIT"
# The detector before the <clinit> fix, which built stage 4 of the results whose
# pipeline_run.log says "code at 516fb46"; whitelist.sh picks the tree per image.
BASELINE_DETECTOR="${BASELINE_DETECTOR:-516fb46}"
rm -rf "$ART/echotrace_$BASELINE_DETECTOR"; mkdir -p "$ART/echotrace_$BASELINE_DETECTOR"
git -C "$LATEST_REPO" archive "$BASELINE_DETECTOR" | tar -x -C "$ART/echotrace_$BASELINE_DETECTOR"
rm -rf "$ART/echotrace_$BASELINE_DETECTOR"/{results,scripts,SysPartCode}
git -C "$LATEST_REPO" rev-parse "$BASELINE_DETECTOR" > "$ART/echotrace_$BASELINE_DETECTOR/COMMIT"

# ------------------------------------------------------- 2. pipeline scripts
copy_scripts() {  # <src repo> <table folder>: scripts/ and the runtime set runc.txt
    rm -rf "$2/scripts"; mkdir -p "$2"
    rsync -a --exclude '__pycache__' --exclude '*.pyc' --exclude '*.bak' "$1/scripts/" "$2/scripts/"
    cp "$1/runc.txt" "$2/runc.txt"
}
log "1_latest_containers/scripts <- ${LATEST_REPO}/scripts"
copy_scripts "$LATEST_REPO" "$ART/1_latest_containers"
# Drop the author-only before/after run of the older detector from stage 4.
python3 - "$ART/1_latest_containers/scripts/run_latest_target.sh" <<'PY'
import re, sys
p = sys.argv[1]; s = open(p).read()
s2 = re.sub(r'\n    if \[ "\$DETECTOR_REPO" != "\$REPO" \]; then\n.*?\n    fi\n', '\n', s, count=1, flags=re.S)
assert s2 != s, "unpatched block not found in run_latest_target.sh"
open(p, 'w').write(s2)
PY
log "2_swat4j_vs_sysjava/scripts <- ${JDK8_REPO}/scripts"
copy_scripts "$JDK8_REPO" "$ART/2_swat4j_vs_sysjava"
python3 "$ART/tools/add_jdk8_official_targets.py" "$ART/2_swat4j_vs_sysjava/scripts"
sed -i 's#syspart-pin/PINNED.md#syspart/README.md#' "$ART/2_swat4j_vs_sysjava/scripts/rerun_syspart_symbolized.sh"
# The JDK 8 runs used runc.txt plus the four runc 1.3.4 init syscalls (README beside it).
cp "$JDK8_REPO"/runc_host_1.3.4_additions.* "$ART/2_swat4j_vs_sysjava/"

# --------------------------------------------------------------- 3. SysPart
# syspart/README.md is maintained in the artifact itself. Only the Egalito crash
# fix is shipped; SysPartCode is used unmodified.
log "syspart/ <- README + ${JDK8_REPO}/syspart-pin/egalito-local.patch"
mkdir -p "$ART/syspart"
rm -f "$ART/syspart/"*.patch "$ART/syspart/PINNED.md"
cp "$JDK8_REPO/syspart-pin/egalito-local.patch" "$ART/syspart/"

# ---------------------------------------------------------------- 4. SWAT4J
log "swat4j/ <- ${SWAT4J_DIR} (scripts + allowlists, not the SWAT4J tool itself)"
rm -rf "$ART/swat4j"; mkdir -p "$ART/swat4j/outputs"
# Scripts of the SWAT4J runs on the ten JDK 8 Debian 10 images (the earlier
# official-image scripts are no longer shipped).
for f in run_swat4j_host_out.sh dynamic_swat4j_jdk8deb.sh package_outputs_jdk8deb.sh \
         README_outputs_jdk8deb.md show_results.py; do
    cp "$SWAT4J_DIR/$f" "$ART/swat4j/"
done
# dynamic_all.sh retries a dynamic run when another container started during it and
# logs each try in dynamic_runs.tsv; the copy finds its folder instead of a fixed path.
sed -E 's#^H=[^;]*;#H="$(cd "$(dirname "$0")" \&\& pwd)";#; s#^for app in (zookeeper[a-z ]*); do#for app in ${*:-\1}; do#' \
    "$SWAT4J_DIR/jdk8_debian10/dynamic_all.sh" > "$ART/swat4j/dynamic_all_jdk8deb.sh"
grep -q 'dirname "$0"' "$ART/swat4j/dynamic_all_jdk8deb.sh" || { echo "dynamic_all.sh: path not replaced"; exit 1; }
cp "$ART/swat4j_extra/setup_swat4j.sh" "$ART/swat4j/"
cp "$ART/swat4j_extra/README.md" "$ART/swat4j/" 2>/dev/null || true
rsync -a "$SWAT4J_DIR/mrx_desktop/" "$ART/swat4j/mrx_desktop/"   # OpenJDK 8 native sources SWAT4J reads
[ ! -f "$SWAT4J_MAPPING" ] || cp "$SWAT4J_MAPPING" "$ART/swat4j/swat4j_mapping.py"
# SWAT4J's outputs on the ten images + SysJava's allowlists; show_results.py prints the table.
bash "$SWAT4J_DIR/package_outputs_jdk8deb.sh" "$ART/swat4j/outputs" >/dev/null

# ------------------------------------------- native-mapping audit (coverage)
log "analysis/native_mapping_audit <- rq1_native_mapping (scripts and write-ups)"
RQ1="${RQ1_DIR:-$TUT/rq1_native_mapping}"
rm -rf "$ART/analysis/native_mapping_audit"; mkdir -p "$ART/analysis/native_mapping_audit/syscall_ablation"
cp "$RQ1"/*.py "$RQ1"/*.sh "$RQ1"/*.md "$ART/analysis/native_mapping_audit/"
cp "$RQ1"/syscall_ablation/*.py "$RQ1"/syscall_ablation/*.sh "$RQ1"/syscall_ablation/*.md \
   "$ART/analysis/native_mapping_audit/syscall_ablation/"

# --------------------------------------------------------------- 5. results
copy_result() {  # <src target dir> <dest target dir>
    local src="$1" dst="$2"
    rm -rf "$dst"; mkdir -p "$dst"
    # -L: some reruns link to folders of the first run; copy what the links point to.
    nice -n 10 rsync -aL \
        --exclude '/Dataset' --exclude '/Dataset_symbolized' \
        --exclude '*.pre_cancel_fix*' --exclude '*.failed*' --exclude '*.incomplete*' \
        --exclude 'jna_detector_work_*/' --exclude 'JDK*_LIBS/' \
        --exclude '*_before_*' \
        "$src/" "$dst/"
    # The captured files (Dataset/: JARs, libraries, executables, the JDK) and the
    # libraries stage 6 added from the container, as split xz archives, so
    # whitelist.sh runs without Docker. Parts stay below GitHub's 100 MB file limit;
    # tar records no owner names.
    if [ -d "$src/Dataset" ]; then
        local U="rup""esh" P="pun""na" K="kou""shik"
        if grep -rlaiE -m1 "$U|$P|$K" "$src/Dataset" >/dev/null 2>&1; then
            echo "identifying string in $src/Dataset; not packed"; exit 1
        fi
        mkdir -p "$dst/dataset"
        (cd "$src" && tar -h --sort=name --owner=0 --group=0 --numeric-owner -cf - Dataset \
            $(ls -d Dataset_symbolized/*/_container_deps 2>/dev/null)) \
            | nice -n 10 xz -T4 -6 | split -b 45M -d -a 2 - "$dst/dataset/Dataset.tar.xz.part"
    fi
    # Notes on executables added by hand to the analysis (not in the capture).
    cp "$src"/Dataset_symbolized/BINARIES_*/ADDED_first_start_binaries.md "$dst/" 2>/dev/null || true
    # Keep the debug-symbol provenance table (which ELF got which debug file).
    if [ -f "$src/Dataset_symbolized/symbols.tsv" ]; then
        cp "$src/Dataset_symbolized/symbols.tsv" "$dst/debug_symbols.tsv"
    fi
}

if [ "$CODE_ONLY" = 0 ]; then
    for t in "${LATEST_TARGETS[@]}"; do
        # KEEP_LATEST=1: keep result folders already built (repacking the datasets takes an hour)
        if [ -n "${KEEP_LATEST:-}" ] && [ -d "$ART/1_latest_containers/results/$t/Binary_Analysis" ]; then continue; fi
        src="$LATEST_REPO/Final_results_latest_versions/$t"
        # ZooKeeper and OrientDB were rerun with the <clinit> fix; that rerun is final.
        [ ! -d "$LATEST_REPO/Final_results_latest_versions_clinit/$t" ] || src="$LATEST_REPO/Final_results_latest_versions_clinit/$t"
        [ -d "$src" ] || { log "latest: $t has no results yet, skipped"; continue; }
        log "1_latest_containers/results/$t"
        copy_result "$src" "$ART/1_latest_containers/results/$t"
    done
    for t in "${JDK8_TARGETS[@]}"; do
        [ "$LATEST_ONLY" = 0 ] || break
        src="$JDK8_REPO/Final_results_JDK8/$t"
        [ -d "$src" ] || { log "jdk8: $t has no results yet, skipped"; continue; }
        log "2_swat4j_vs_sysjava/sysjava_results/$t"
        copy_result "$src" "$ART/2_swat4j_vs_sysjava/sysjava_results/$t"
    done
    for t in "${JDK8_OFFICIAL_TARGETS[@]}"; do
        dst="$ART/2_swat4j_vs_sysjava/sysjava_results/$t"
        if [ "$LATEST_ONLY" = 0 ] && [ -n "$JDK8_OFFICIAL_SRC" ] && [ -d "$JDK8_OFFICIAL_SRC/$t" ]; then
            log "2_swat4j_vs_sysjava/sysjava_results/$t <- $JDK8_OFFICIAL_SRC"
            copy_result "$JDK8_OFFICIAL_SRC/$t" "$dst"
        else
            log "jdk8: $t placeholder (results pending)"
            rm -rf "$dst"; mkdir -p "$dst"
            printf 'Results pending: this folder is filled by tools/build_artifact.sh\n(JDK8_OFFICIAL_SRC=<results dir>) once the final run of %s is done.\n' "$t" > "$dst/PENDING.md"
        fi
    done
    # Detector before/after <clinit> fix and the -verbose:jni recall benchmark.
    for extra in _before_clinit_fix _after_clinit_fix _native_recall; do
        [ "$LATEST_ONLY" = 0 ] || break
        [ -d "$JDK8_REPO/Final_results_JDK8/$extra" ] || continue
        rm -rf "$ART/2_swat4j_vs_sysjava/sysjava_results/$extra"
        rsync -a "$JDK8_REPO/Final_results_JDK8/$extra/" "$ART/2_swat4j_vs_sysjava/sysjava_results/$extra/"
    done
fi

# ------------------------------------------------- Docker images and digests
log "docker_images/ (digests, Dockerfiles)"
bash "$ART/tools/docker_images.sh" "$ART" "$JDK8_REPO"
# Host, kernel, Docker/runc/libseccomp and tool versions of the runs (the image
# tarballs themselves, 5 GB, are not in the repository).
DOCKER_RECORD="${DOCKER_RECORD:-$TUT/docker_images}"
cp "$DOCKER_RECORD/ENVIRONMENT.md" "$DOCKER_RECORD/environment.json" "$ART/docker_images/" 2>/dev/null || true
rm -f "$ART/1_latest_containers/images.tsv" "$ART/2_swat4j_vs_sysjava/images.tsv"

# Without --with-results every result folder is an empty placeholder; with
# --with-latest-results only those of table 2.
placeholder() {  # <dir> <target>
    rm -rf "$1"; mkdir -p "$1"
    printf 'Results pending for %s.\nAdded by tools/build_artifact.sh --with-results once the final run is done.\n' "$2" > "$1/PENDING.md"
}
if [ "$CODE_ONLY" = 1 ]; then
    for t in "${LATEST_TARGETS[@]}"; do placeholder "$ART/1_latest_containers/results/$t" "$t"; done
    rm -rf "$ART/1_latest_containers/tables" "$ART/1_latest_containers/STATUS.md"
fi
if [ "$CODE_ONLY" = 1 ] || [ "$LATEST_ONLY" = 1 ]; then
    rm -rf "$ART/2_swat4j_vs_sysjava/sysjava_results"
    for t in "${JDK8_TARGETS[@]}" "${JDK8_OFFICIAL_TARGETS[@]}"; do
        placeholder "$ART/2_swat4j_vs_sysjava/sysjava_results/$t" "$t"
    done
    rm -rf "$ART"/2_swat4j_vs_sysjava/sysjava_results/_* \
           "$ART/2_swat4j_vs_sysjava/tables" "$ART/2_swat4j_vs_sysjava/STATUS.md" \
           "$ART/swat4j/RESULTS.md" "$ART/swat4j/paper_table.md" "$ART/swat4j/paper_table.tex"
fi

# ------------------------------------------------------------- 6. anonymise
log "anonymising text files"
bash "$ART/tools/anonymise.sh" "$ART"
# Call graphs and function lists are the bulk of the results (up to ~50 MB
# each); gzip after anonymising so the text pass sees them. whitelist.sh reads
# them gzipped.
find "$ART/1_latest_containers/results" "$ART/2_swat4j_vs_sysjava/sysjava_results" \
    \( -name callgraph.json -o -name allfunctions.txt \) -type f -print0 2>/dev/null | nice -n 10 xargs -0 -r -P 4 gzip -9f

# ------------------------------------------------------- 7. tables + status
status_md() {  # <out.md> <results dir> <target>...: last pipeline stage + runtime check
    local out="$1" root="$2"; shift 2
    {
        echo "# Status of the shipped results"
        echo
        echo "Generated by tools/build_artifact.sh on $(date -u '+%Y-%m-%d %H:%M UTC')."
        echo "An image is complete when its last stage is \"done\" and the profile file exists."
        echo
        echo "| Image | Last stage logged | Profile | Runs under profile |"
        echo "|---|---|---|---|"
        for t in "$@"; do
            d="$root/$t"
            if [ ! -d "$d" ]; then echo "| $t | not started | - | - |"; continue; fi
            if [ -f "$d/PENDING.md" ]; then echo "| $t | results pending | - | - |"; continue; fi
            st="$(grep -ah '^===== \[' "$d/pipeline_run.log" 2>/dev/null | tail -1 | sed -E 's/^===== \[[^]]*\] [^ ]+ stage ([^:]+):.*/\1/' || true)"
            prof="no"; [ -f "$d/Binary_Analysis/syscalls_output_$t/$t.json" ] && prof="yes"
            res="$(cat "$d/seccomp_runtime_test.log" "$d/Binary_Analysis/syscalls_output_$t/seccomp_runtime_test.log" 2>/dev/null \
                   | grep -a 'RESULT=' | tail -1 | sed 's/.*RESULT=//' || true)"
            echo "| $t | ${st:-?} | $prof | ${res:--} |"
        done
    } > "$out"
}

if [ "$CODE_ONLY" = 0 ]; then
    status_md "$ART/1_latest_containers/STATUS.md" "$ART/1_latest_containers/results" "${LATEST_TARGETS[@]}"
    log "tables"
    python3 "$ART/tools/make_tables.py" latest "$ART/1_latest_containers/results" \
        --runtime "$ART/1_latest_containers/runc.txt" --out "$ART/1_latest_containers/tables" || true
    # The final Table III (paper format) and the remaining not-found natives with reasons.
    cp "$LATEST_REPO"/tables/tableIII_latest_rerun_*.tex "$LATEST_REPO"/tables/tableIII_latest_rerun_*.pdf \
       "$LATEST_REPO"/tables/notfound_natives_latest_*.pdf "$ART/1_latest_containers/tables/" 2>/dev/null || true
fi
if [ "$CODE_ONLY" = 0 ] && [ "$LATEST_ONLY" = 0 ]; then
    status_md "$ART/2_swat4j_vs_sysjava/STATUS.md" "$ART/2_swat4j_vs_sysjava/sysjava_results" "${JDK8_TARGETS[@]}" "${JDK8_OFFICIAL_TARGETS[@]}"
    python3 "$ART/tools/make_tables.py" jdk8 "$ART/2_swat4j_vs_sysjava/sysjava_results" \
        --runtime "$ART/2_swat4j_vs_sysjava/runc.txt" "$ART/2_swat4j_vs_sysjava/runc_host_1.3.4_additions.txt" --out "$ART/2_swat4j_vs_sysjava/tables" || true
fi

bash "$ART/tools/anonymise.sh" --check "$ART"
links="$(find "$ART" -path "$ART/.git" -prune -o -path "$ART/work" -prune -o -type l -print)"
[ -z "$links" ] || { echo "symlinks in the artifact (targets may name the author):"; echo "$links"; exit 1; }
du -sh "$ART"
log "done"
