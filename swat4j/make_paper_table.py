#!/usr/bin/env python3
"""Build the SysJava vs SWAT4J (static + dynamic) table in the layout of
sysjava-paper/icse27/tables/results.tex.

Usage: make_paper_table.py <echotrace_results_dir> <rerun_static_dir> <dynamic_dir> <out_prefix>
Writes <out_prefix>.tex and <out_prefix>.md
"""
import csv
import json
import os
import sys

# paper column order: (swat4j name, results folder, label, version, image, distro, jdk)
APPS = [
    ("zookeeper", "zookeeper_3.4.14", "Zookeeper", "3.4.14", "zookeeper:3.4.14", "Debian 10", "8"),
    ("tomcat", "tomcat_7.0", "Tomcat", "7.0", "tomcat:7.0", "Debian 10", "8"),
    ("cassandra", "cassandra_3.0.29", "Cassandra", "3.0.29", "cassandra:3.0.29", "Debian 10", "8"),
    ("jetty", "jetty_9.4.51", "Jetty", "9.4.51", "jetty:9.4.51", "Debian 10", "8"),
    ("storm", "storm_2.4.0", "Storm", "2.4.0", "storm:2.4.0", "Debian 10", "8"),
    ("orientdb", "orientdb_3.2.19", "OrientDB", "3.2.19", "orientdb:3.2.19", "Debian 10", "8"),
    ("elasticsearch", "elasticsearch_7.5.2", "Elasticsearch", "7.5.2", "elasticsearch:7.5.2", "Debian 10", "8"),
    ("solr", "solr_8.7.0", "Solr", "8.7.0", "solr:8.7.0", "Debian 10", "8"),
    ("groovy", "groovy_4.0.0", "Groovy", "4.0.0", "groovy:4.0.0", "Debian 10", "8"),
    ("jruby", "jruby_9.4.2.0", "JRuby", "9.4.2.0", "jruby:9.4.2.0", "Debian 10", "8"),
]
DOCKER = ("Host Ubuntu 22.04, kernel 5.15. Static: OpenJDK 8u504, objdump 2.38, glibc 2.35. "
          "Dynamic: Docker 29.1.3 (containerd 2.2.1, runc 1.3.4), strace 5.16")
# ausyscall name -> Docker/libseccomp name for the same syscall number
ALIASES = {"pread": "pread64", "pwrite": "pwrite64"}


def read_list(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return {ALIASES.get(l.strip(), l.strip()) for l in f if l.strip()}


def read_sysjava(et_dir, folder):
    path = os.path.join(et_dir, folder, "Binary_Analysis", f"syscalls_output_{folder}", f"{folder}.json")
    with open(path) as f:
        rules = json.load(f)["syscalls"]
    return set().union(*[set(r["names"]) for r in rules if r.get("action") == "SCMP_ACT_ALLOW"])


def main():
    et_dir, static_dir, dyn_dir, out = sys.argv[1:5]
    timing = {}
    with open(os.path.join(dyn_dir, "timing.csv")) as f:
        for r in csv.DictReader(f):
            timing[r["app"]] = r

    cols = []
    for name, folder, *_ in APPS:
        sj = read_sysjava(et_dir, folder)
        st = read_list(os.path.join(static_dir, f"{name}_syscalls.txt"))
        dy = read_list(os.path.join(dyn_dir, f"{name}_result.txt"))
        full = (st | dy) if st is not None and dy is not None else None
        c = {"sysjava": len(sj), "static": st, "dynamic": dy, "full": full,
             "startup": timing.get(name, {}).get("seconds"), "stop": timing.get(name, {}).get("stopped_by")}
        if full is not None:
            c.update(both=len(sj & full), only_sj=len(sj - full), only_sw=len(full - sj))
        cols.append(c)

    def cell(c, key, fmt="{}"):
        v = c.get(key)
        if v is None:
            return "---"
        if isinstance(v, set):
            v = len(v)
        return fmt.format(v)

    rows = [
        ("SysJava Total Syscalls ($A$)", lambda c: cell(c, "sysjava"), True),
        ("SWAT4J (Static + Dynamic) ($B$)", lambda c: cell(c, "full"), True),
        ("\\quad Static (JTracer, host)", lambda c: "crash" if c["static"] is None else cell(c, "static"), False),
        ("\\quad Dynamic (containerd startup trace)", lambda c: cell(c, "dynamic"), False),
        ("$A \\cap B$", lambda c: cell(c, "both"), False),
        ("$A \\setminus B$", lambda c: cell(c, "only_sj"), False),
        ("$B \\setminus A$", lambda c: cell(c, "only_sw"), False),
    ]

    tex = [
        "% SysJava vs SWAT4J (static + dynamic), generated by swat4j/make_paper_table.py",
        "\\begin{table*}[tp!]",
        "\\centering",
        "\\caption{Syscall allowlists of \\sysname and SWAT4J (static + dynamic) for the ten",
        "SWAT4J containers. SWAT4J was rerun unmodified: JTracer static analysis on the",
        "container artefacts, and its dynamic analysis by tracing containerd with",
        f"\\texttt{{strace -f -c}} during container startup. {DOCKER}.}}",
        "\\label{tab:swat4j-full}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l" + "r" * len(APPS) + "}",
        "\\toprule",
        " & " + " & ".join(f"\\textbf{{{a[2]}}}" for a in APPS) + " \\\\",
        " & " + " & ".join(a[3] for a in APPS) + " \\\\",
        " & " + " & ".join(a[5] for a in APPS) + " \\\\",
        " & " + " & ".join(f"JDK {a[6]}" for a in APPS) + " \\\\",
        "\\midrule",
    ]
    for label, fn, bold in rows:
        vals = [fn(c) for c in cols]
        if bold:
            vals = [f"\\textbf{{{v}}}" for v in vals]
            label = label.replace("SysJava", "\\textbf{\\sysname}").replace("SWAT4J (", "\\textbf{SWAT4J} (")
        tex.append(f"{label}\n  & " + " & ".join(vals) + " \\\\")
        if label.startswith("\\quad Dynamic"):
            tex.append("\\midrule")
    tex += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table*}", ""]
    with open(out + ".tex", "w") as f:
        f.write("\n".join(tex))

    md = ["| | " + " | ".join(a[2] for a in APPS) + " |", "|---" * (len(APPS) + 1) + "|",
          "| Version | " + " | ".join(a[3] for a in APPS) + " |",
          "| Distro | " + " | ".join(a[5] for a in APPS) + " |",
          "| JDK | " + " | ".join(a[6] for a in APPS) + " |"]
    for label, fn, bold in rows:
        label = (label.replace("\\quad ", "↳ ").replace("\\cap", "∩")
                 .replace("\\setminus", "∖").replace("$", ""))
        md.append(f"| {'**' + label + '**' if bold else label} | " + " | ".join(fn(c) for c in cols) + " |")
    md.append(f"\n{DOCKER}. SWAT4J's `pread` is aliased to `pread64` (same syscall, ausyscall naming).")
    with open(out + ".md", "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
